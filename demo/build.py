"""Build the online demo into _site/.

The demo runs the real panel (custom_components/.../frontend/kde-panel.js)
against a simulated Home Assistant with made-up devices. This script copies
the demo shell and the panel next to each other and writes icons.js with only
the Material Design Icons the pages use.

    python demo/build.py
    python -m http.server -d _site 8000
"""

from __future__ import annotations

import json
import re
import shutil
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEMO = ROOT / "demo"
PANEL = ROOT / "custom_components" / "kdeforhomeassistant" / "frontend" / "kde-panel.js"
SITE = ROOT / "_site"
MDI_URL = "https://cdn.jsdelivr.net/npm/@mdi/js@7.4.47/mdi.js"
SHELL_FILES = ("index.html", "demo.js", "demo.css")


def camel(name: str) -> str:
    return "mdi" + "".join(part.capitalize() for part in name.split("-"))


def main() -> None:
    if SITE.exists():
        shutil.rmtree(SITE)
    SITE.mkdir()
    for name in SHELL_FILES:
        shutil.copy(DEMO / name, SITE / name)
    shutil.copy(PANEL, SITE / "kde-panel.js")
    shutil.copy(PANEL.parent.parent / "brand" / "icon.png", SITE / "favicon.png")

    names: set[str] = set()
    for path in (PANEL, DEMO / "demo.js", DEMO / "index.html"):
        names.update(re.findall(r"mdi:([a-z0-9-]+)", path.read_text()))

    with urllib.request.urlopen(MDI_URL, timeout=60) as response:
        source = response.read().decode()
    paths = dict(re.findall(r'export var (mdi\w+) = "([^"]+)"', source))
    icons, missing = {}, []
    for name in sorted(names):
        if camel(name) in paths:
            icons[name] = paths[camel(name)]
        else:
            missing.append(name)
    if missing:
        sys.exit(f"Unknown icons: {', '.join(missing)}")
    (SITE / "icons.js").write_text(
        "// Generated by demo/build.py from @mdi/js (Apache 2.0).\n"
        f"export const ICONS = {json.dumps(icons, indent=0)};\n"
    )
    print(f"Built {SITE} with {len(icons)} icons")


if __name__ == "__main__":
    main()
